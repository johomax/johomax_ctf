#!/usr/bin/env python3
"""Turn a sim/walkdump.nim mask into a Nim module the policy can embed.

    scripts/br_mask_to_nim.py <mask.txt> <out.nim> [--name BrGen1339]

Encoding: `Runs` is a flat seq of uint16 run lengths, rows concatenated in
order, each row alternating walkable/blocked and STARTING with a walkable
run (a row that begins blocked opens with a zero-length walkable run); every
row's runs sum to the width. `Sum` is a FNV-1a of the mask bits so a decoder
can prove it rebuilt the same picture. A 3211x1713 map is ~17k runs.
"""

import argparse
import re


def fnv1a(bits: str) -> int:
    h = 0xCBF29CE484222325
    for ch in bits.encode():
        h ^= ch
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mask")
    ap.add_argument("out")
    ap.add_argument("--name", default="BrGen1339")
    args = ap.parse_args()
    lines = open(args.mask).read().split("\n")
    w, h = map(int, lines[0].split())
    rows = lines[1:1 + h]
    assert all(len(r) == w for r in rows), "ragged mask"
    runs = []
    for r in rows:
        row_runs = []
        walk = True
        for m in re.finditer(r"1+|0+", r):
            is_walk = m.group()[0] == "1"
            if is_walk != walk:
                row_runs.append(0)
                walk = not walk
            row_runs.append(len(m.group()))
            walk = not walk
        assert sum(row_runs) == w
        runs.extend(row_runs)
        runs.append(0xFFFF)  # row terminator
    assert max(x for x in runs if x != 0xFFFF) < 0xFFFF
    digest = fnv1a("".join(rows))
    body = []
    line = "    "
    for x in runs:
        tok = f"{x},"
        if len(line) + len(tok) > 78:
            body.append(line.rstrip())
            line = "    "
        line += tok + " "
    body.append(line.rstrip())
    src = f'''## GENERATED by scripts/br_mask_to_nim.py from sim/walkdump.nim -- do not edit.
##
## The walkability mask of the league's pinned battle-royale map
## ({args.name}, {w}x{h}), as the engine's own `walkMask` bits. Run-length
## rows: alternating walkable/blocked run lengths starting with a walkable
## run (a zero opens a row that starts blocked), each row closed by 0xFFFF.
## `{args.name}Sum` is FNV-1a over the row-major '0'/'1' text a decoder can
## re-check. Regenerate after any engine pin move:
##   sim/walkdump.nim --engine .engine --config sim/paintbot_br.json --out m.txt
##   scripts/br_mask_to_nim.py m.txt bot/baseline/brmap.nim

const
  {args.name}W* = {w}
  {args.name}H* = {h}
  {args.name}Sum* = 0x{digest:016X}'u64
  {args.name}Runs*: array[{len(runs)}, uint16] = [
{chr(10).join(body)}
  ]
'''
    open(args.out, "w").write(src)
    print(f"{w}x{h} runs {len(runs)} bytes {len(src)} sum {digest:016X}")


if __name__ == "__main__":
    main()

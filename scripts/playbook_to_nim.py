#!/usr/bin/env python3
"""Emit one embedded Nim byte array for a Season 2 play module."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


def nim_ident(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("wasm", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--name", required=True)
    args = parser.parse_args()

    data = args.wasm.read_bytes()
    if len(data) > 262_144:
        raise SystemExit(f"{args.wasm}: module exceeds 256 KiB")
    ident = "Playbook" + nim_ident(args.name)
    digest = hashlib.sha256(data).hexdigest()
    rows = []
    for start in range(0, len(data), 20):
        rows.append("    " + ", ".join(str(value) for value in data[start:start + 20]))

    output = (
        "## GENERATED by scripts/build_playbook.sh -- do not edit.\n\n"
        "const\n"
        f'  {ident}Name* = "{args.name}"\n'
        f'  {ident}Sha256* = "{digest}"\n'
        f"  {ident}Bytes*: array[{len(data)}, uint8] = [\n"
        + ",\n".join(rows)
        + "\n  ]\n"
    )
    args.output.write_text(output)


if __name__ == "__main__":
    main()
